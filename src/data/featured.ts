import { createGame } from '../engine/level';
import type { GameData, GameRules, PublishedGame } from '../engine/types';

const T0 = Date.UTC(2026, 0, 1);

function rows(...r: string[]): { width: number; height: number; tiles: string } {
  const width = r[0].length;
  for (const line of r) {
    if (line.length !== width) throw new Error(`row length mismatch: "${line}"`);
  }
  return { width, height: r.length, tiles: r.join('') };
}

function make(
  id: string,
  title: string,
  description: string,
  theme: PublishedGame['theme'],
  hero: string,
  rules: GameRules,
  grid: { width: number; height: number; tiles: string },
  stats: { plays: number; likes: number },
  collection?: string,
  extra: Partial<GameData> = {},
): PublishedGame {
  return {
    ...createGame({
      id,
      title,
      description,
      author: 'Weblox',
      authorAvatar: '🧊',
      theme,
      hero,
      rules,
      kidMode: false,
      createdAt: T0,
      updatedAt: T0,
      ...grid,
      ...extra,
    }),
    publishedAt: T0,
    plays: stats.plays,
    likes: stats.likes,
    featured: true,
    collection,
  };
}

